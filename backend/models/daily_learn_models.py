"""
Pydantic models for Phase 4 — Daily Learn Orchestration.
"""

from typing import List, Optional
from pydantic import BaseModel, Field

from .study_plan_models import ScheduledTopic
from .rag_models import SourceRef


class DailyLearnRequest(BaseModel):
    """
    Request body for POST /api/v1/daily-learn/today.
    """
    courseCode: str = Field(description="Course code to retrieve the saved study plan")
    dayNumber: int = Field(description="The current day number in the study plan (1-N)")
    topK: int = Field(
        default=5,
        description="Number of RAG chunks to retrieve per topic",
        ge=1,
        le=10,
    )


class LearningContent(BaseModel):
    """
    The generated educational content for the day's topics.
    """
    title: str = Field(description="Title of the learning content (usually the topic name(s))")
    explanation: str = Field(description="The educational explanation generated by the LLM")
    keyPoints: List[str] = Field(
        default_factory=list,
        description="Optional list of key points (if the LLM output can be structured, otherwise empty)"
    )
    sources: List[SourceRef] = Field(description="The syllabus sources used to generate this content")


class DailyLearnResponse(BaseModel):
    """
    Response from POST /api/v1/daily-learn/today.
    """
    success: bool = True
    dayNumber: int
    topics: List[ScheduledTopic] = Field(description="The topics scheduled for this day")
    learningContent: LearningContent
